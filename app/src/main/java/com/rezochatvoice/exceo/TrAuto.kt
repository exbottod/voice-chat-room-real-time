/**
 * Penerjemah otomatis Indonesia -> Inggris.
 *
 * Dipakai tr() sebagai cadangan terakhir: kalau sebuah teks tidak ada di kamus
 * utama, teks itu tetap tampil Inggris (bukan Indonesia) lewat dua tahap:
 *  1. cocokkan frasa utuh (kamus frasa di bawah),
 *  2. kalau tidak ada, terjemahkan per kata memakai kamus kata.
 *
 * Hasil disimpan di cache supaya aman dipanggil berkali-kali dari Compose.
 */
fun autoEn(s: String): String {
    if (s.isBlank()) return s
    AUTO_CACHE[s]?.let { return it }
    val v = hitungTerjemahan(s)
    AUTO_CACHE[s] = v
    return v
}

private val AUTO_CACHE = java.util.concurrent.ConcurrentHashMap<String, String>()

private val FRASA: List<Pair<String, String>> by lazy {
    TR_AUTO_PHRASE.entries
        .map { it.key.lowercase() to it.value }
        .sortedByDescending { it.first.length }
}

private fun hitungTerjemahan(s: String): String {
    TR_AUTO_PHRASE[s.lowercase()]?.let { return it }
    val tanpaNewline = s.replace("\\n", " ")
    var out = tanpaNewline
    for ((k, v) in FRASA) {
        if (out.length >= k.length && out.lowercase().contains(k)) out = gantiFrasa(out, k, v)
    }
    return terjemahKata(out)
}

private fun gantiFrasa(s: String, kunci: String, nilai: String): String = try {
    Regex("(?<![A-Za-z0-9])" + Regex.escape(kunci) + "(?![A-Za-z0-9])", RegexOption.IGNORE_CASE)
        .replace(s, Regex.escapeReplacement(nilai))
} catch (e: Exception) {
    s
}

private fun terjemahKata(s: String): String {
    val sb = StringBuilder(s.length + 16)
    var i = 0
    while (i < s.length) {
        val c = s[i]
        if (c.isLetter()) {
            var j = i
            while (j < s.length && s[j].isLetter()) j++
            val kata = s.substring(i, j)
            val en = TR_AUTO_WORD[kata.lowercase()]
            if (en == null) {
                sb.append(kata)
            } else if (kata[0].isUpperCase()) {
                sb.append(en.replaceFirstChar { it.uppercase() })
            } else {
                sb.append(en)
            }
            i = j
        } else {
            sb.append(c)
            i++
        }
    }
    return sb.toString()
}

